EXPECTED_QUESTION_COUNTS = {1: 7, 2: 9, 3: 10, 4: 25, 5: 16, 6: 26, 7: 38, 8: 23}


def test_parses_all_eight_lectures():
    rules, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    assert [l.lecture_number for l in lectures] == [1, 2, 3, 4, 5, 6, 7, 8]


def test_rules_match_the_real_documents_stated_requirements():
    rules, _ = parse_assignment(REAL_DOCUMENT_TEXT)
    assert rules.min_pages == 5
    assert rules.font_size == 12
    assert rules.min_questions == 3


def test_every_lecture_gets_its_full_question_count():
    # Lectures 4, 6, and 7 mix "11. Text" and "11.Text" (no space) numbering
    # styles — a regex boundary mismatch here used to silently merge a
    # no-space item into the end of the previous question's text instead
    # of starting a new one, undercounting lecture 4 as 10 instead of 25.
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    counts = {l.lecture_number: len(l.questions) for l in lectures}
    assert counts == EXPECTED_QUESTION_COUNTS


def test_lecture_1_combines_main_and_additional_topic_in_one_block():
    # The document names Lecture 1's "дополнительная" (additional) topic
    # inline within the same header rather than as a separate numbered
    # lecture — parsed into `additional_topic` (not left mixed into `topic`,
    # see test_lecture_1_splits_additional_topic_out below), and all 7
    # questions spanning both sub-topics still belong to lecture_number=1.
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    lecture1 = next(l for l in lectures if l.lecture_number == 1)
    assert "Основы теории информации" in lecture1.topic
    assert lecture1.questions[0] == "В чем отличие энтропийного оценивания информации и алфавитного?"
    assert lecture1.questions[-1] == "Описать сравнительные характеристики протоколов UDP, TCP. Привести примеры использования."


def test_lecture_1_splits_additional_topic_out():
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    lecture1 = next(l for l in lectures if l.lecture_number == 1)
    assert lecture1.additional_topic == "Протоколы стека TCP."
    assert "Протоколы стека TCP" not in lecture1.topic


def test_lectures_without_an_additional_topic_have_it_empty():
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    lecture2 = next(l for l in lectures if l.lecture_number == 2)
    assert lecture2.additional_topic == ""


def test_lecture_4_no_space_items_are_split_correctly():
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    lecture4 = next(l for l in lectures if l.lecture_number == 4)
    assert lecture4.questions[9] == "В чем особенность протокола RIP и как он работает?"
    assert lecture4.questions[10] == "Описать таблицу маршрутизации."
    assert lecture4.questions[11] == "В чем особенность протокола OSPF и как он работает?"
    assert lecture4.questions[-1] == "Какие стандарты для разъемов RJ-45 есть?"


def test_last_lecture_excludes_title_page_boilerplate():
    _, lectures = parse_assignment(REAL_DOCUMENT_TEXT)
    lecture8 = next(l for l in lectures if l.lecture_number == 8)
    assert lecture8.questions[-1] == "Что такое DarkNet?"
    assert "МИНИСТЕРСТВО" not in lecture8.questions[-1]
